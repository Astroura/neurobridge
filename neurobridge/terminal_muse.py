"""User-visible Terminal fallback using the same bundled MuseLSL command."""
import os
from pathlib import Path
import shlex
import subprocess
import sys
from runtime import worker
from platform_support import support_dir,FileLock,worker_options


def terminal_running():
    lock = FileLock(support_dir()/'terminal-muse.lock')
    if not lock.acquire(): return True
    lock.close()
    return False


def launch():
    if sys.platform == 'win32':
        # A direct argument vector avoids cmd.exe quoting and shell metacharacters.
        env=dict(os.environ,PYTHONIOENCODING='utf-8',PYTHONUTF8='1',PYINSTALLER_RESET_ENVIRONMENT='1')
        env.pop('NEUROBRIDGE_STOP_FILE',None)
        subprocess.Popen(worker('terminal-stream','--backend','bleak','--lsltime'),env=env,**worker_options(visible=True))
        return None
    if sys.platform != 'darwin':
        raise ValueError('The Terminal startup button is available on macOS.')
    folder = support_dir()
    folder.mkdir(parents=True, exist_ok=True)
    path = folder/'Start-Muse.command'
    command = worker('terminal-stream', '--backend', 'bleak', '--lsltime')
    path.write_text('#!/bin/zsh\n# Generated by NeuroBridge. No separate Python installation needed.\n'
                    'export NEUROBRIDGE_SUPPORT_DIR='+shlex.quote(str(folder))+'\n'
                    +shlex.join(command)+'\n', encoding='utf-8')
    path.chmod(0o700)
    try:
        subprocess.run(['/usr/bin/open', '-a', 'Terminal', str(path)], check=True, timeout=10)
    except (subprocess.SubprocessError, OSError) as exc:
        raise ValueError('Could not open Terminal. Try opening '+str(path)+' manually.') from exc
    return path


def run():
    lock = FileLock(support_dir()/'terminal-muse.lock')
    if not lock.acquire():
        print('NeuroBridge already has a Muse console running. Use that window.', flush=True)
        return
    try:
        print('NeuroBridge Muse startup: keep this window open while collecting.\n'
              'Press Control+C here to disconnect. Return to NeuroBridge and click Start live check.\n', flush=True)
        from muselsl.cli import CLI
        sys.argv = ['muselsl', 'stream'] + sys.argv[1:]
        CLI('stream')
    finally: lock.close()
